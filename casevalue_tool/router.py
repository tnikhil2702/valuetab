        ("Accident and Injury", ["accident injury", "accident and injury", "accident & injury"]),
        ("AZ Imaging", ["az imaging", "arizona imaging", "arizona advanced imaging"]),
        ("Athletico PT", ["athletico", "athletico pt"]),
