def dedupe_rows(rows, mode):
    seen = set()
    result = []

    for row in rows:
        if mode == "recovery":
            key = (
                normalize_name(row.get("source")),
                money_to_decimal(row.get("amount")),
            )
        elif mode == "case_expense":
            key = (
                normalize_name(row.get("provider")),
                str(row.get("date", "")).strip(),
                money_to_decimal(row.get("amount")),
            )
        else:
            key = (
                normalize_name(row.get("provider")),
                str(row.get("date", "")).strip(),
                money_to_decimal(row.get("due")),
            )

        if key in seen:
            continue

        seen.add(key)
        result.append(row)

    return result

