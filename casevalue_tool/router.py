@router.post("/ocr-document")
async def ocr_document(
    file: UploadFile = File(...),
    caseNumber: str = Form(""),
    fileName: str = Form(""),
    fileId: str = Form(""),
    webUrl: str = Form(""),
    x_api_key: str = Header("")
):
    if x_api_key != API_KEY:
        raise HTTPException(status_code=401, detail="Unauthorized")

    original_name = fileName or file.filename or "document.pdf"
    suffix = os.path.splitext(original_name)[1].lower()

    with tempfile.NamedTemporaryFile(delete=False, suffix=suffix) as tmp:
        tmp.write(await file.read())
        tmp_path = tmp.name

    try:
        if suffix == ".pdf":
            full_text, pages = extract_pdf(tmp_path)
        elif suffix == ".docx":
            full_text, pages = extract_docx(tmp_path)
        else:
            return {
                "caseNumber": caseNumber,
                "fileName": original_name,
                "fileId": fileId,
                "webUrl": webUrl,
                "status": "unsupported_file_type",
                "fullText": "",
                "merged_text": "",
                "pages": [],
                "hints": {},
            }

        return {
            "caseNumber": caseNumber,
            "fileName": original_name,
            "fileId": fileId,
            "webUrl": webUrl,
            "status": "success",
            "fullText": full_text,
            "merged_text": full_text,
            "pages": pages,
            "hints": detect_hints(full_text),
            "characterCount": len(full_text),
            "structuredDocument": build_structured_document_evidence({
                "file_id": fileId,
                "file_name": original_name,
                "pages": pages,
            }),
        }

    except Exception as e:
        return {
            "caseNumber": caseNumber,
            "fileName": original_name,
            "fileId": fileId,
            "webUrl": webUrl,
            "status": "error",
            "error": str(e),
            "fullText": "",
            "merged_text": "",
            "pages": [],
            "hints": {},
        }

    finally:
        try:
            os.remove(tmp_path)
        except Exception:
            pass


